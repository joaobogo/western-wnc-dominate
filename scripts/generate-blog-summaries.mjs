#!/usr/bin/env node
// Extracts the N most recent blog posts (metadata only) so the homepage
// BlogInsights component doesn't pull the full blogs.ts (~478 KB) into the
// main bundle. Runs on predev/prebuild.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const SRC = resolve("src/data/blogs.ts");
const OUT = resolve("src/data/blog-summaries.generated.ts");
const N = 12;

const src = readFileSync(SRC, "utf8");
// Anchor on `slug:` then look ahead within the same object for other fields.
const slugRe = /\bslug:\s*"([^"]+)"/g;
const grab = (field, chunk) => {
  const re = new RegExp(`\\b${field}:\\s*"((?:[^"\\\\]|\\\\.)*)"`);
  const m = chunk.match(re);
  return m ? m[1] : "";
};

const posts = [];
let m;
while ((m = slugRe.exec(src)) !== null) {
  const start = m.index;
  // Look at the next ~2500 chars (a single blog object) for co-located fields.
  const chunk = src.slice(start, start + 2500);
  const slug = m[1];
  const title = grab("title", chunk);
  const excerpt = grab("excerpt", chunk);
  const category = grab("category", chunk);
  const date = grab("date", chunk);
  const readTime = grab("readTime", chunk);
  if (slug && title && date) {
    posts.push({ id: slug, slug, title, excerpt, category, date, readTime });
  }
}

posts.sort((a, b) => (a.date < b.date ? 1 : -1));
const top = posts.slice(0, N);

const body = `// AUTO-GENERATED by scripts/generate-blog-summaries.mjs — do not edit.
// Lightweight metadata for the homepage BlogInsights section so the full
// blogs.ts payload is only loaded on /blog and /blog/:slug routes.
export interface BlogSummary {
  id: string;
  slug: string;
  title: string;
  excerpt: string;
  category: string;
  date: string;
  readTime: string;
}

export const blogSummaries: BlogSummary[] = ${JSON.stringify(top, null, 2)};
`;

writeFileSync(OUT, body);
console.log(`[blog-summaries] wrote ${top.length} entries → ${OUT}`);