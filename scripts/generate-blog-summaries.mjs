#!/usr/bin/env node
// Extracts the N most recent blog posts (metadata only) so the homepage
// BlogInsights component doesn't pull the full blogs.ts (~478 KB) into the
// main bundle. Runs on predev/prebuild.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const SRC = resolve("src/data/blogs.ts");
const OUT = resolve("src/data/blog-summaries.generated.ts");
const N = 12;

const src = readFileSync(SRC, "utf8");
// Parse each object block { ... , }, keeping only the fields we need.
const objectRe = /\{\s*id:\s*"([^"]+)",[\s\S]*?slug:\s*"([^"]+)",[\s\S]*?title:\s*"((?:[^"\\]|\\.)*)",[\s\S]*?excerpt:\s*"((?:[^"\\]|\\.)*)",[\s\S]*?category:\s*"([^"]+)",[\s\S]*?date:\s*"([^"]+)",[\s\S]*?readTime:\s*"([^"]+)"/g;

const posts = [];
let m;
while ((m = objectRe.exec(src)) !== null) {
  posts.push({
    id: m[1], slug: m[2], title: m[3], excerpt: m[4],
    category: m[5], date: m[6], readTime: m[7],
  });
}

posts.sort((a, b) => (a.date < b.date ? 1 : -1));
const top = posts.slice(0, N);

const body = `// AUTO-GENERATED by scripts/generate-blog-summaries.mjs — do not edit.
// Lightweight metadata for the homepage BlogInsights section so the full
// blogs.ts payload is only loaded on /blog and /blog/:slug routes.
export interface BlogSummary {
  id: string;
  slug: string;
  title: string;
  excerpt: string;
  category: string;
  date: string;
  readTime: string;
}

export const blogSummaries: BlogSummary[] = ${JSON.stringify(top, null, 2)};
`;

writeFileSync(OUT, body);
console.log(`[blog-summaries] wrote ${top.length} entries → ${OUT}`);